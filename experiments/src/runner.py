"""Single entry point for every numerical result retained in the report."""

from __future__ import annotations

import argparse
import platform
from pathlib import Path
import sys
import time
from typing import Any, Mapping

import matplotlib
import numpy as np
import scipy

from . import affine_rank_one, box_qp, escape
from .common import METHOD_LABELS, load_json, write_csv, write_json


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONFIG = ROOT / "config" / "report.json"
RESULTS = ROOT / "results"


def _expected_pair(config: Mapping[str, Any], method: str) -> tuple[int, int]:
    expected = config["expected"][method]
    return int(expected[0]), int(expected[1])


def _check_report_counts(
    rows: list[dict[str, Any]], config: Mapping[str, Any], strict: bool = True
) -> list[str]:
    """Fail loudly if a run no longer reproduces the printed Table 6.1.

    With ``strict=False`` the mismatches are returned instead of raised; this is
    meant for platforms where floating-point differences move a borderline
    endpoint across the acceptance tolerance.
    """

    mismatches = []
    for row in rows:
        expected = _expected_pair(config, str(row["method"]))
        observed = (int(row["accepted_endpoints"]), int(row["distinct_roots"]))
        if observed != expected:
            message = (
                f"report-count mismatch for {row['family']}/{row['method']}: "
                f"observed {observed}, expected {expected}"
            )
            if strict:
                raise RuntimeError(message + " (rerun with --no-strict to write results to results_local/)")
            mismatches.append(message)
    return mismatches


def _write_table_fragment(rows: list[dict[str, Any]], path: Path) -> None:
    """Write only the six body rows consumed by the LaTeX table."""

    family_labels = {"affine rank one": "affine rank one", "box QP": "box QP"}
    lines = ["% Generated by python -m sdg_report_experiments; do not edit by hand."]
    for family in ("affine rank one", "box QP"):
        family_rows = [row for row in rows if row["family"] == family]
        for index, row in enumerate(family_rows):
            first_column = (
                rf"\multirow{{{len(family_rows)}}}{{*}}{{{family_labels[family]}}}"
                if index == 0
                else ""
            )
            lines.append(
                f"{first_column} & {METHOD_LABELS[str(row['method'])]} & "
                f"{row['accepted_endpoints']}/{row['starts']} & "
                f"{row['distinct_roots']}/{row['catalog_roots']} \\\\" 
            )
        if family != "box QP":
            lines.append(r"\midrule")
    # Keeping the closing rule in the generated fragment avoids leaving a
    # booktabs ``\noalign`` command across an external-file boundary.
    lines.append(r"\bottomrule")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _serialize_catalog(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    serialized: list[dict[str, Any]] = []
    for row in rows:
        serialized.append(
            {
                key: value
                for key, value in row.items()
                if key not in {"negative_interiors", "wrong_bounds"}
            }
        )
    return serialized


def reproduce(config_path: Path = DEFAULT_CONFIG, strict: bool = True) -> dict[str, Any]:
    config = load_json(config_path)
    # A non-strict run never overwrites the published artifacts.
    results = RESULTS if strict else ROOT / "results_local"
    seed = int(config["seed"])
    started = time.perf_counter()

    affine = affine_rank_one.run(config["affine_rank_one"], seed)
    box = box_qp.run(config["box_qp"], seed)
    summary = [*affine["summary"], *box["summary"]]
    mismatches = _check_report_counts(affine["summary"], config["affine_rank_one"], strict)
    mismatches += _check_report_counts(box["summary"], config["box_qp"], strict)

    tables = results / "tables"
    figures = results / "figures"
    candidates = results / "candidates"
    write_csv(tables / "branch_recovery_summary.csv", summary)
    write_csv(candidates / "affine_rank_one_endpoints.csv", affine["candidates"])
    write_csv(candidates / "box_qp_endpoints.csv", box["candidates"])
    write_csv(tables / "affine_rank_one_catalog.csv", affine["catalog"])
    write_csv(tables / "box_qp_catalog.csv", _serialize_catalog(box["catalog"]))
    _write_table_fragment(summary, tables / "branch_recovery_rows.tex")

    escape_rows = escape.box_escape_catalog(box["problem"], box["catalog"])
    flat_rows = escape.hessian_flat_rows(config["hessian_flat"])
    write_csv(tables / "box_escape_catalog.csv", escape_rows)
    write_csv(tables / "hessian_flat_decreases.csv", flat_rows)
    escape.plot_box_escape(box["problem"], escape_rows, figures)
    escape.plot_box_states(box["problem"], figures)
    escape.plot_hessian_flat(flat_rows, figures)

    metadata = {
        "config": config_path.relative_to(ROOT).as_posix(),
        "elapsed_seconds": time.perf_counter() - started,
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "numpy": np.__version__,
        "scipy": scipy.__version__,
        "matplotlib": matplotlib.__version__,
        "affine": affine["metadata"],
        "box": box["metadata"],
        "report_count_mismatches": mismatches,
    }
    write_json(results / "run_metadata.json", metadata)
    return {"summary": summary, "metadata": metadata, "mismatches": mismatches, "results": results}


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Reproduce the numerical results retained in the internship report."
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=DEFAULT_CONFIG,
        help="JSON configuration (default: config/report.json)",
    )
    parser.add_argument(
        "--no-strict",
        action="store_true",
        help="report count mismatches instead of failing and write outputs to results_local/",
    )
    return parser


def main() -> int:
    arguments = _parser().parse_args()
    result = reproduce(arguments.config.resolve(), strict=not arguments.no_strict)
    if result["mismatches"]:
        print("Completed with report-count deviations (outputs in results_local/):")
        for message in result["mismatches"]:
            print(f"  {message}")
    else:
        print("Reproduced Table 6.1 and Figures 6.1--6.3")
    for row in result["summary"]:
        print(
            f"  {row['family']:16s} {row['method']:22s} "
            f"accepted={row['accepted_endpoints']}/{row['starts']} "
            f"roots={row['distinct_roots']}/{row['catalog_roots']}"
        )
    print(f"  elapsed={result['metadata']['elapsed_seconds']:.2f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
